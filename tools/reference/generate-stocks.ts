/**
 * Emits `StockProfiles.generated.swift` from the TypeScript stock definitions.
 *
 * Run: `npm run generate:stocks`
 *
 * The emulsion *model* is hand-written Swift, because an algorithm ported by
 * hand is an algorithm someone has read and understood. The stock *data* is
 * generated, because 60 profiles of dense numeric constants is transcription
 * work, and hand transcription of numeric constants has exactly one failure
 * mode: a digit nobody notices until a hash disagrees.
 *
 * Generating also means the Swift data cannot silently drift from the
 * TypeScript — regenerate, and any change shows up as a reviewable diff.
 */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { ALL_STOCK_PROFILES } from '../../src/lib/processing/filters/stock-profiles';
import type { FilmStockProfile } from '../../src/lib/processing/filters/film-model';

const OUT = resolve(
  import.meta.dirname,
  '../../apple/Sources/DarkroomCore/Film/StockProfiles.generated.swift',
);

/** Swift case names for `FilmCategory`. */
const CATEGORY: Record<string, string> = {
  classic: 'classic',
  social: 'social',
  portrait: 'portrait',
  kodak: 'kodak',
  fuji: 'fuji',
  cinema: 'cinema',
  bw: 'blackAndWhite',
};

/**
 * Formats a number as a Swift `Double` literal that round-trips exactly.
 *
 * JavaScript's default `toString` already produces the shortest representation
 * that parses back to the same IEEE-754 double, which is precisely the
 * guarantee needed — but integers must gain a `.0` so Swift infers `Double`
 * rather than `Int`.
 */
const num = (value: number): string =>
  Number.isInteger(value) ? `${value}.0` : String(value);

/** Escapes a string for a Swift literal. */
const str = (value: string): string =>
  `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** Converts a snake/kebab id to a lowerCamelCase Swift identifier. */
const identifier = (id: string): string => {
  const camel = id.replace(/[-_]([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  // `1977` and `5293`-style ids cannot begin a Swift identifier.
  return /^[0-9]/.test(camel) ? `stock${camel}` : camel;
};

const curveLiteral = (curve: FilmStockProfile['curves']['r']): string =>
  `ChannelCurve(gamma: ${num(curve.gamma)}, toe: ${num(curve.toe)}, ` +
  `toeLift: ${num(curve.toeLift)}, shoulder: ${num(curve.shoulder)}, ` +
  `shoulderStrength: ${num(curve.shoulderStr)}, gain: ${num(curve.gain)})`;

const stockLiteral = (profile: FilmStockProfile): string => {
  const m = profile.dyeMatrix;
  const grain = profile.grain
    ? `FilmGrainSpec(amount: ${num(profile.grain.amount)}, ` +
      `warmth: ${num(profile.grain.warmth)}, size: ${num(profile.grain.size)})`
    : 'nil';

  const category = CATEGORY[profile.category];
  if (!category) throw new Error(`Unmapped category '${profile.category}' on '${profile.id}'`);

  return `    public static let ${identifier(profile.id)} = FilmStock(
        id: ${str(profile.id)},
        name: ${str(profile.label)},
        category: .${category},
        summary: ${str(profile.description)},
        redCurve: ${curveLiteral(profile.curves.r)},
        greenCurve: ${curveLiteral(profile.curves.g)},
        blueCurve: ${curveLiteral(profile.curves.b)},
        dyeMatrix: ColorMatrix3x3(
            ${num(m[0][0])}, ${num(m[0][1])}, ${num(m[0][2])},
            ${num(m[1][0])}, ${num(m[1][1])}, ${num(m[1][2])},
            ${num(m[2][0])}, ${num(m[2][1])}, ${num(m[2][2])}
        ),
        scanner: .${profile.scanner},
        shadowHue: ${num(profile.shadowHue)},
        shadowTint: ${num(profile.shadowTint)},
        highlightHue: ${num(profile.highlightHue)},
        highlightTint: ${num(profile.highlightTint)},
        latitude: ${num(profile.latitude)},
        saturation: ${num(profile.saturation)},
        vibrance: ${num(profile.vibrance)},
        halation: ${num(profile.halation)},
        halationWarmth: ${num(profile.halationWarmth)},
        grain: ${grain},
        preservesSkinTones: ${profile.skinPreserve === true},
        isStylized: ${profile.stylized === true}
    )`;
};

const main = () => {
  const profiles = ALL_STOCK_PROFILES;

  const byCategory = new Map<string, FilmStockProfile[]>();
  for (const profile of profiles) {
    const list = byCategory.get(profile.category) ?? [];
    list.push(profile);
    byCategory.set(profile.category, list);
  }

  const sections: string[] = [];
  for (const [category, list] of byCategory) {
    sections.push(`    // MARK: - ${CATEGORY[category]}\n`);
    sections.push(list.map(stockLiteral).join('\n\n'));
    sections.push('');
  }

  const allNames = profiles.map((p) => `        .${identifier(p.id)},`).join('\n');

  const source = `// Generated by tools/reference/generate-stocks.ts — do not edit.
//
// Run \`npm run generate:stocks\` from the repository root to regenerate.
//
// The emulsion model in FilmModel.swift is hand-written. This file is only the
// data it runs on: ${profiles.length} stock profiles transcribed mechanically from the
// TypeScript definitions, so no constant can be mistyped on the way across.

import Foundation

extension FilmStock {

${sections.join('\n')}
    // MARK: - Catalogue

    /// Every built-in stock, in the order the picker presents them.
    public static let allStocks: [FilmStock] = [
${allNames}
    ]

    /// Looks up a stock by its stable identifier.
    public static func stock(id: String) -> FilmStock? {
        stocksByID[id]
    }

    private static let stocksByID: [String: FilmStock] =
        Dictionary(uniqueKeysWithValues: allStocks.map { ($0.id, $0) })
}
`;

  writeFileSync(OUT, source, 'utf8');
  console.log(`Wrote ${profiles.length} stock profiles to ${OUT.replace(process.cwd() + '/', '')}`);

  const counts = [...byCategory].map(([c, l]) => `${c}=${l.length}`).join('  ');
  console.log(`  ${counts}`);
};

main();
